// Step 3-C: Pure TypeScript Contracts for Smart Table Mapping & Auto Column Matching Wizard
import type {
  AppealTermType,
  JalaliAcademicMonth,
  SidaEnrollmentStatus,
} from '../../types/domain';

export type SmartImportTargetType = 'students' | 'teachers' | 'classes' | 'sida_grades';

export type SmartImportFieldKey =
  | 'nationalId'
  | 'fullName'
  | 'firstName'
  | 'lastName'
  | 'fatherName'
  | 'studentCode'
  | 'sidaStudentCode'
  | 'parentName'
  | 'parentMobile'
  | 'birthDateJalali'
  | 'gradeLabel'
  | 'className'
  | 'section'
  | 'roomCode'
  | 'capacity'
  | 'enrollmentStatus'
  | 'emergencyNotes'
  | 'personnelCode'
  | 'mobile'
  | 'specialty'
  | 'weeklyQuotaPeriods'
  | 'subject'
  | 'continuousScore'
  | 'finalScore'
  | 'term'
  | 'jalaliMonth';

export type MappingTargetSelection = SmartImportFieldKey | '__ignore__';

export interface SmartImportFieldDefinition {
  key: SmartImportFieldKey;
  labelFa: string;
  required: boolean;
  supportsDefault: boolean;
  supportsAutoGenerate: boolean;
  autoGenerateHintFa?: string;
  defaultPlaceholderFa?: string;
  targets: SmartImportTargetType[];
}

export type ParsedSourceFormat = 'csv' | 'tsv' | 'html_sida' | 'paste';

export interface HeaderRowCandidate {
  rowIndex: number;
  score: number;
  nonEmptyCount: number;
  dictionaryHits: number;
  looksLikeData: boolean;
  previewText: string;
}

export interface ParsedTableResult {
  rows: string[][];
  sourceFormat: ParsedSourceFormat;
  delimiter: ',' | ';' | '\t' | 'html';
  fileName: string;
  totalRows: number;
  columnCount: number;
  detectedHeaderRowIndex: number;
  headerCandidates: HeaderRowCandidate[];
}

export type ColumnMatchConfidence = 'exact' | 'smart' | 'unmatched';

export type DetectedCellPattern =
  | 'national_id'
  | 'iranian_mobile'
  | 'jalali_date'
  | 'grade_score'
  | 'text'
  | 'empty';

export interface ColumnMappingItem {
  colIndex: number;
  headerLabel: string;
  samples: string[];
  targetField: MappingTargetSelection;
  confidence: ColumnMatchConfidence;
  matchReasonFa: string;
  detectedPattern: DetectedCellPattern;
}

export type MissingCellPolicyMode =
  | 'keep_existing'
  | 'use_default'
  | 'auto_generate'
  | 'quarantine';

export interface MissingCellPolicyConfig {
  mode: MissingCellPolicyMode;
  defaultValue: string;
}

export type MissingCellPolicyMap = Partial<Record<SmartImportFieldKey, MissingCellPolicyConfig>>;

export type DuplicateHandlingStrategy = 'smart_merge' | 'fill_empty_only' | 'skip_duplicates';

export interface SecondaryJoinConfig {
  enabled: boolean;
  fileName: string;
  parsedTable: ParsedTableResult | null;
  headerRowIndex: number;
  nationalIdColIndex: number;
  selectedAppendColIndices: number[];
  appendColumnMappings: Record<number, MappingTargetSelection>;
}

export interface JoinExecutionSummary {
  joinedCount: number;
  unmatchedPrimaryCount: number;
  unmatchedSecondaryCount: number;
  secondaryValidKeyCount: number;
}

export type ImportRowBucket = 'valid' | 'needs_fix' | 'quarantine';

export type ImportRowOperation = 'create' | 'update' | 'skip';

export interface ValidatedImportRow {
  rowId: string;
  sourceRowNumber: number; // 1-based original row index in file
  bucket: ImportRowBucket;
  operation: ImportRowOperation;
  existingRecordId?: string;
  existingRecordLabel?: string;
  joinedFromSecondary: boolean;
  rawValues: Partial<Record<SmartImportFieldKey, string>>;
  normalizedValues: Partial<Record<SmartImportFieldKey, string>>;
  warnings: string[];
  errors: string[];
  fixableFields: SmartImportFieldKey[];
  autoGeneratedCredentialsNote?: string;
}

export interface SmartImportDryRunSummary {
  totalDataRows: number;
  validCount: number;
  createCount: number;
  updateCount: number;
  skipCount: number;
  needsFixCount: number;
  quarantineCount: number;
  joinedCount: number;
  newClassesToCreate: string[];
  newAccountsToCreateCount: number;
}

export interface SmartImportQuarantineReportRow {
  sourceRowNumber: number;
  identifier: string;
  displayName: string;
  errors: string[];
}

export interface SmartImportCommitReceipt {
  batchId: string;
  executedAtIso: string;
  executedAtJalali: string;
  executedAtTimeHm: string;
  complexId: string;
  schoolId: string;
  schoolName: string;
  academicYearId: string;
  targetType: SmartImportTargetType;
  targetLabelFa: string;
  actorName: string;
  actorRoleFa: string;
  sourceFileName: string;
  secondaryFileName?: string;
  createdCount: number;
  updatedCount: number;
  skippedCount: number;
  newClassesCreatedCount: number;
  joinedCount: number;
  quarantinedCount: number;
  newAccountsCreatedCount: number;
  auditLogEntryHash?: string;
  quarantinedRows: SmartImportQuarantineReportRow[];
}

export interface SmartImportCommitPayload {
  complexId: string;
  schoolId: string;
  academicYearId: string;
  targetType: SmartImportTargetType;
  sourceFileName: string;
  secondaryFileName?: string;
  duplicateStrategy: DuplicateHandlingStrategy;
  missingPolicies: MissingCellPolicyMap;
  validRows: ValidatedImportRow[];
  quarantinedRows: ValidatedImportRow[];
  joinedCount: number;
  defaultTerm?: AppealTermType;
  defaultMonth?: JalaliAcademicMonth;
  defaultEnrollmentStatus?: SidaEnrollmentStatus;
}
